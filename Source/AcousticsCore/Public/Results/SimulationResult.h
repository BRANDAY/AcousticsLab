struct FBeamTree;

/** A receiver handed to a solver: position in meters and sphere radius. */
struct ACOUSTICSCORE_API FSolverReceiver
{
	FString Name;
	FVector3d Position = FVector3d::ZeroVector;
	double Radius = Acoustics::DefaultReceiverRadius;

	FSolverReceiver() = default;
	FSolverReceiver(const FString& InName, const FVector3d& InPosition, double InRadius = Acoustics::DefaultReceiverRadius)
		: Name(InName)
		, Position(InPosition)
		, Radius(InRadius)
	{
	}
};

/** One entry of a path into a receiver sphere (the path continues: receivers are transparent). */
struct ACOUSTICSCORE_API FPathReceiverHit
{
	int32 ReceiverIndex = INDEX_NONE;

	/** Reflection order of the segment that entered the sphere (= index of that segment in Points). */
	int32 Order = 0;

	/** Entry point on the sphere surface, m, and the arrival time, s. */
	FVector3d EntryPoint = FVector3d::ZeroVector;
	double TimeSeconds = 0.0;

	/** Energy of band 0 deposited, relative to the emitted E0. */
	double Energy = 0.0;
};

/**
 * One traced path kept for visualization (M3): the emission point, every reflection point and the end point.
 * Segment i runs from Points[i] to Points[i + 1] with reflection order i and starts with SegmentEnergies[i].
 */
struct ACOUSTICSCORE_API FPathSample
{
	/** Emission index of the ray (its Fibonacci-sphere direction and random stream). */
	int32 RayIndex = INDEX_NONE;

	TArray<FVector3d> Points;

	/** Energy of band 0 at the start of every segment, relative to the emitted E0 (Points.Num() - 1 entries). */
	TArray<double> SegmentEnergies;

	/** Every receiver entry along the path, in path order. */
	TArray<FPathReceiverHit> ReceiverHits;

	/** Number of reflections the path went through. */
	int32 Order = 0;

	/** Energy of band 0 at the end of the path, relative to the emitted E0. */
	double FinalEnergy = 0.0;

	bool bReachedReceiver = false;

	/** Reflection order of the segment that first entered a receiver, INDEX_NONE when none did. */
	int32 FirstReceiverHitOrder = INDEX_NONE;
	int32 FirstReceiverIndex = INDEX_NONE;

	int32 NumSegments() const { return FMath::Max(0, Points.Num() - 1); }

	/** First entry into ReceiverIndex (any receiver when INDEX_NONE), nullptr when the path never entered it. */
	const FPathReceiverHit* FindReceiverHit(int32 ReceiverIndex) const;
};

/**
 * One deterministic specular path from the image-source solver (SPEC §2.4) or a beam containing the receiver (SPEC §2.5.6):
 * the energy Prod(1 - alpha_i) r^2 / (4 d^2) arrives at d / c, d = distance from the receiver to the image source (= beam apex).
 */
struct ACOUSTICSCORE_API FEarlyReflection
{
	/** Number of reflections (0 = direct sound, listed only when the solver reports it this way). */
	int32 Order = 0;
	double TimeSeconds = 0.0;
	double Distance = 0.0;

	/** Energy deposited per band, relative to the emitted energy. */
	double Energy[Acoustics::NumBands];

	/** Image source of the path (the beam apex for beam contributions). */
	FVector3d ImageSource = FVector3d::ZeroVector;

	/** Source, every reflection point, receiver (Order + 2 points). */
	TArray<FVector3d> Path;

	/** Triangles hit, in path order from the source. */
	TArray<int32> Triangles;

	/** Node of FSimulationResult::BeamTree that produced the contribution, INDEX_NONE for the image-source solver. */
	int32 BeamNode = INDEX_NONE;

	/** Index into FSimulationResult::ImageSources, INDEX_NONE for the beam tracer. */
	int32 ImageSourceIndex = INDEX_NONE;

	FEarlyReflection();
};

/** An image source generated by FImageSourceSolver (SPEC §2.4), valid or not, for the sphere visualization. */
struct ACOUSTICSCORE_API FImageSourceSample
{
	int32 Order = 0;
	FVector3d Position = FVector3d::ZeroVector;

	/** Reflecting surfaces as one triangle index per surface (the first triangle of the coplanar group), in path order. */
	TArray<int32> Triangles;

	/** Index of the previous image of the chain (INDEX_NONE for first-order images). */
	int32 Parent = INDEX_NONE;

	/** At least one receiver of the run has a valid path from this image. */
	bool bValidForAnyReceiver = false;
};

/**
 * Purely specular ray deposits of one reflection sequence at one receiver (M8, hybrid bookkeeping of FRayTracer with
 * FRayTracerSettings::bRecordSpecularArrivals): every ray that entered the receiver sphere after reflecting specularly
 * off the same surfaces in the same order. The beams of the hybrid find the same path as one FEarlyReflection.
 */
struct ACOUSTICSCORE_API FSpecularRayArrival
{
	/** FRayTracer::SurfaceSequenceKey of the reflecting surfaces (coplanar triangle groups) in path order. */
	uint64 SequenceKey = 0;

	int32 Order = 0;

	/** Image-source delay to the receiver centre d' / c, s (the delay the beams report for the path). */
	double TimeSeconds = 0.0;

	/**
	 * Image source of the path (first ray of the group): Origin - Direction * PathLength in the unfolded space. Two
	 * sequences can share it (reflections off two perpendicular walls commute: A-B and B-A), and a receiver sphere may be
	 * reached through both while the beams report the one valid at its centre - match beams and rays by image source.
	 */
	FVector3d ImageSource = FVector3d::ZeroVector;

	/** Rays of the sequence that entered the sphere and their deposited energy (band 0, relative to the emitted energy). */
	int32 NumHits = 0;
	double Energy = 0.0;

	/** The deposits went to ExcludedHistogram (early-specular: order <= ExcludeSpecularMaxOrder and TimeSeconds <= ExcludeSpecularMaxSeconds). */
	bool bExcluded = false;
};

/** Histogram, metrics and direct-sound data of one receiver. */
struct ACOUSTICSCORE_API FReceiverResult
{
	FString Name;
	FVector3d Position = FVector3d::ZeroVector;
	double Radius = Acoustics::DefaultReceiverRadius;

	FEnergyHistogram Histogram;
	FRoomMetrics Metrics;

	/** Source-receiver distance, m, and the direct-sound arrival d / c, s (also the time origin of C50 / C80). */
	double DirectDistance = 0.0;
	double DirectArrivalSeconds = 0.0;
	bool bDirectOccluded = false;

	/** Direct-sound energy deposited (0 when occluded), band 0. */
	double DirectEnergy = 0.0;

	/** Ray segments that entered the sphere and deposited energy. */
	int64 NumRayHits = 0;

	/** Deterministic early reflections (image sources, beams) sorted by arrival time; empty for the ray tracer. */
	TArray<FEarlyReflection> EarlyReflections;

	/** Nodes of FSimulationResult::BeamTree whose beam contains the receiver (order 0 included), for the visualizer. */
	TArray<int32> ContainingBeamNodes;

	/**
	 * Ray tracer with FRayTracerSettings::ExcludeSpecularMaxOrder > 0 (M8 hybrid): the early-specular deposits that were
	 * kept out of Histogram (Histogram + ExcludedHistogram = the plain ray-tracer histogram). Empty otherwise.
	 */
	FEnergyHistogram ExcludedHistogram;
	int64 NumExcludedHits = 0;

	/** Purely specular ray deposits of order 1..ExcludeSpecularMaxOrder grouped by reflection sequence, sorted by time (bRecordSpecularArrivals). */
	TArray<FSpecularRayArrival> SpecularRayArrivals;
};

struct ACOUSTICSCORE_API FSimulationTiming
{
	double SetupSeconds = 0.0;
	double TraceSeconds = 0.0;
	double MetricsSeconds = 0.0;
	double TotalSeconds = 0.0;
	int32 NumWorkers = 0;
};

struct ACOUSTICSCORE_API FSimulationResult
{
	FString SolverName;
	bool bSuccess = false;
	bool bCancelled = false;
	FString Error;

	FVector3d SourcePosition = FVector3d::ZeroVector;
	TArray<FReceiverResult> Receivers;

	/**
	 * Up to MaxPathsForVisualization rays in emission order: every PathSampleStride-th ray (FRayTracer::PathSampleStride),
	 * so the samples cover the whole emission sphere. Sampling never changes the histograms.
	 */
	TArray<FPathSample> Paths;
	int32 PathSampleStride = 1;

	FSimulationTiming Timing;

	int32 NumRays = 0;
	int32 NumTriangles = 0;

	/** Ray segments traced (one per reflection plus the final segment of every ray). */
	int64 NumSegments = 0;

	/** Rays that left the scene without hitting anything. */
	int32 NumRaysEscaped = 0;

	/** Mean number of reflections per ray. */
	double MeanOrder = 0.0;

	/** Image sources of FImageSourceSolver (all generated ones, valid or not). */
	TArray<FImageSourceSample> ImageSources;
	int32 NumImageSources = 0;
	int32 NumValidImagePaths = 0;

	/** Beam tree of FBeamTracer (built once per source, queried per receiver); null for the other solvers. */
	TSharedPtr<const FBeamTree> BeamTree;
	int32 NumRootBeams = 0;
	int32 NumBeamNodes = 0;

	const FReceiverResult* FindReceiver(const FString& Name) const;
	FString Describe() const;
};

/** Shared between the solver thread and the caller: completed work units and the cancel flag. */
struct ACOUSTICSCORE_API FSolverProgress
{
	std::atomic<int64> Completed{ 0 };
	std::atomic<int64> Total{ 0 };
	std::atomic<bool> bCancelRequested{ false };

	void Reset(int64 InTotal);
	void Add(int64 Count) { Completed.fetch_add(Count, std::memory_order_relaxed); }
	float Fraction() const;
	void RequestCancel() { bCancelRequested.store(true, std::memory_order_relaxed); }
	bool IsCancelRequested() const { return bCancelRequested.load(std::memory_order_relaxed); }
};
